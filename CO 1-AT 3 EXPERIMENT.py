import numpy as np
import matplotlib.pyplot as plt

# Create Dataset
X = np.arange(1, 21, dtype=float)
X = X / np.max(X)          # Normalize inputs
Y = 2 * X + 1              # y = 2x + 1

learning_rate = 0.001
epochs = 100
batch_sizes = [1, 5, 10]

plt.figure(figsize=(8,5))

for batch_size in batch_sizes:

    # Initialize parameters
    w = 0.0
    b = 0.0
    losses = []

    for epoch in range(epochs):

        # Shuffle dataset
        indices = np.random.permutation(len(X))
        X_shuffled = X[indices]
        Y_shuffled = Y[indices]

        # Mini-Batch Training
        for i in range(0, len(X), batch_size):

            X_batch = X_shuffled[i:i + batch_size]
            Y_batch = Y_shuffled[i:i + batch_size]

            # Prediction
            Y_pred = w * X_batch + b

            # Gradients
            dw = (-2 / len(X_batch)) * np.sum(X_batch * (Y_batch - Y_pred))
            db = (-2 / len(X_batch)) * np.sum(Y_batch - Y_pred)

            # Update parameters
            w -= learning_rate * dw
            b -= learning_rate * db

        # Calculate loss after each epoch
        Y_pred_all = w * X + b
        loss = np.mean((Y - Y_pred_all) ** 2)
        losses.append(loss)

    plt.plot(losses, linewidth=2, label=f"Batch Size = {batch_size}")

plt.title("Mini-Batch Gradient Descent")
plt.xlabel("Epochs")
plt.ylabel("Mean Squared Error (Loss)")
plt.legend()
plt.grid(True)
plt.show()

# Print final parameters
print("Final Weight:", round(w, 4))
print("Final Bias:", round(b, 4))
print("Final Loss:", round(losses[-1], 6))

import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_classification
from sklearn.model_selection import train_test_split
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import accuracy_score
from scipy.spatial.distance import pdist

dimensions = [2, 5, 10, 20, 50]
avg_distances = []
accuracies = []

for dim in dimensions:

    X, y = make_classification(
        n_samples=500,
        n_features=dim,
        n_informative=max(2, dim//2),
        n_redundant=0,
        random_state=42
    )

    # Average distance between points
    avg_distance = np.mean(pdist(X))
    avg_distances.append(avg_distance)

    # Train-Test Split
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.3, random_state=42
    )

    # KNN Model
    model = KNeighborsClassifier(n_neighbors=5)
    model.fit(X_train, y_train)

    y_pred = model.predict(X_test)

    accuracy = accuracy_score(y_test, y_pred)
    accuracies.append(accuracy)

    print(f"Dimensions = {dim}, Average Distance = {avg_distance:.2f}, Accuracy = {accuracy:.2f}")

# Plot Results
plt.figure(figsize=(10,4))

plt.subplot(1,2,1)
plt.plot(dimensions, avg_distances, marker='o')
plt.title("Dimension vs Average Distance")
plt.xlabel("Dimensions")
plt.ylabel("Average Distance")
plt.grid(True)

plt.subplot(1,2,2)
plt.plot(dimensions, accuracies, marker='o', color='red')
plt.title("Dimension vs Accuracy")
plt.xlabel("Dimensions")
plt.ylabel("Accuracy")
plt.grid(True)

plt.tight_layout()
plt.show()