import numpy as np

# Input and Target
x = np.array([1.0, 2.0])
target = 1

# Initial Weights and Bias
w = np.array([0.5, -0.4])
b = 0.2

learning_rate = 0.1

# Sigmoid Function
def sigmoid(z):
    return 1 / (1 + np.exp(-z))

# Derivative of Sigmoid
def sigmoid_derivative(y):
    return y * (1 - y)

# Forward Propagation
z = np.dot(x, w) + b
output = sigmoid(z)

# Error
error = target - output

# Gradient
delta = error * sigmoid_derivative(output)

# Update Weights and Bias
w = w + learning_rate * delta * x
b = b + learning_rate * delta

print("Updated Weights:", np.round(w, 3))
print("Updated Bias:", round(b, 3))

